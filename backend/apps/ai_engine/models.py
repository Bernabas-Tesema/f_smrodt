import uuid
from django.db import models
from django.utils import timezone


class AIProviderConfig(models.Model):
    PROVIDER_CHOICES = [
        ('gemini', 'Google Gemini'),
        ('openai', 'OpenAI GPT-4o'),
        ('anthropic', 'Anthropic Claude'),
    ]

    STATUS_CHOICES = [
        ('active', 'Active'),
        ('degraded', 'Degraded'),
        ('disabled', 'Disabled'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    provider = models.CharField(max_length=32, choices=PROVIDER_CHOICES, unique=True)
    display_name = models.CharField(max_length=80)
    model_name = models.CharField(max_length=80, default='gemini-2.5-flash')
    is_active = models.BooleanField(default=False)
    is_default = models.BooleanField(default=False)
    api_key_env_var = models.CharField(max_length=64, default='GEMINI_API_KEY')
    max_tokens = models.PositiveIntegerField(default=1024)
    temperature = models.FloatField(default=0.2)
    
    # Operational health metrics
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='active')
    avg_latency_ms = models.FloatField(default=280.0)
    uptime_pct = models.FloatField(default=99.9)
    total_tokens_used = models.BigIntegerField(default=0)
    total_cost_usd = models.DecimalField(max_digits=10, decimal_places=4, default=0.0000)
    error_count_24h = models.PositiveIntegerField(default=0)
    last_health_check = models.DateTimeField(default=timezone.now)

    class Meta:
        db_table = 'smrod_ai_providers'
        ordering = ['provider']

    def __str__(self):
        return f'{self.get_provider_display()} ({self.model_name})'


class AIPrediction(models.Model):
    PREDICTION_TYPE_CHOICES = [
        ('theft', 'Theft Detection'),
        ('crash', 'Crash Assistance'),
        ('risk', 'Risk Anomaly'),
        ('general', 'General Security Analysis'),
    ]

    RISK_LEVEL_CHOICES = [
        ('low', 'Low'),
        ('medium', 'Medium'),
        ('high', 'High'),
        ('critical', 'Critical'),
    ]

    STATUS_CHOICES = [
        ('pending', 'Pending Review'),
        ('acknowledged', 'Acknowledged'),
        ('investigating', 'Investigating'),
        ('confirmed', 'Confirmed Incident'),
        ('false_positive', 'Marked False Positive'),
        ('resolved', 'Resolved'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    vehicle = models.ForeignKey('vehicles.Vehicle', on_delete=models.CASCADE, related_name='ai_predictions')
    prediction_type = models.CharField(max_length=32, choices=PREDICTION_TYPE_CHOICES, db_index=True)
    
    # Scoring & confidence
    risk_score = models.PositiveSmallIntegerField(help_text='Deterministic or evaluated risk score 0-100')
    risk_level = models.CharField(max_length=16, choices=RISK_LEVEL_CHOICES, default='medium')
    confidence_score = models.FloatField(help_text='AI model confidence score 0.0 to 1.0')
    
    # Reasoning & context
    title = models.CharField(max_length=200)
    ai_explanation = models.TextField(help_text='Natural language explanation generated by the AI provider')
    recommended_actions = models.JSONField(default=list, help_text='List of suggested operator actions')
    contributing_factors = models.JSONField(default=dict, help_text='Key contributing sensor/telemetry factors')
    raw_telemetry_snapshot = models.JSONField(default=dict, help_text='Frozen telemetry state at detection time')
    
    # Audit & triage status
    status = models.CharField(max_length=24, choices=STATUS_CHOICES, default='pending', db_index=True)
    false_positive_reason = models.TextField(blank=True, null=True)
    assigned_operator = models.CharField(max_length=120, blank=True, null=True)
    
    # AI provenance
    provider_used = models.CharField(max_length=32, default='gemini')
    model_version = models.CharField(max_length=64, default='gemini-2.5-flash')
    inference_latency_ms = models.PositiveIntegerField(default=320)
    
    # Timestamps
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    updated_at = models.DateTimeField(auto_now=True)
    acknowledged_at = models.DateTimeField(null=True, blank=True)
    resolved_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = 'smrod_ai_predictions'
        ordering = ['-created_at']

    def __str__(self):
        return f'[{self.prediction_type.upper()}] {self.vehicle.plate_number} (Risk {self.risk_score} - {self.risk_level})'


class VehicleRiskScore(models.Model):
    CATEGORY_CHOICES = [
        ('low', 'Low (0-29)'),
        ('medium', 'Medium (30-59)'),
        ('high', 'High (60-79)'),
        ('critical', 'Critical (80-100)'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    vehicle = models.OneToOneField('vehicles.Vehicle', on_delete=models.CASCADE, related_name='ai_risk_score')
    
    # Deterministic weighted score (0-100)
    current_score = models.PositiveSmallIntegerField(default=15)
    category = models.CharField(max_length=16, choices=CATEGORY_CHOICES, default='low')
    
    # Factor breakdown percentages/weights
    factor_breakdown = models.JSONField(
        default=dict,
        help_text='Weights: theft_risk (35%), crash_history (25%), geofence_breaches (20%), sensor_tampering (20%)'
    )
    
    score_delta_7d = models.SmallIntegerField(default=0, help_text='Score change over the past 7 days')
    primary_risk_factor = models.CharField(max_length=120, default='Normal operations')
    last_calculated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'smrod_vehicle_risk_scores'
        ordering = ['-current_score']

    def __str__(self):
        return f'{self.vehicle.plate_number}: {self.current_score} ({self.category})'


class AIInferenceLog(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    provider = models.CharField(max_length=32)
    model = models.CharField(max_length=64)
    endpoint = models.CharField(max_length=120)
    prompt_tokens = models.PositiveIntegerField(default=0)
    completion_tokens = models.PositiveIntegerField(default=0)
    total_tokens = models.PositiveIntegerField(default=0)
    cost_usd = models.DecimalField(max_digits=8, decimal_places=5, default=0.00000)
    latency_ms = models.PositiveIntegerField()
    status_code = models.PositiveSmallIntegerField(default=200)
    is_success = models.BooleanField(default=True)
    error_message = models.TextField(blank=True, null=True)
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        db_table = 'smrod_ai_inference_logs'
        ordering = ['-created_at']
